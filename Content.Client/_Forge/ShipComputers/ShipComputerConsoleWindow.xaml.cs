using Content.Shared._Forge.ShipComputers;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Forge.ShipComputers;

[GenerateTypedNameReferences]
public sealed partial class ShipComputerConsoleWindow : FancyWindow
{
    public ShipComputerConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(ShipComputerConsoleState state)
    {
        ConnectionLabel.Text = Loc.GetString(state.Connected ? "ship-computer-console-connected" : "ship-computer-console-disconnected");
        ProcessingLabel.Text = Loc.GetString("ship-computer-console-processing",
            ("used", state.UsedProcessingPower), ("total", state.ProcessingPower));
        PowerLabel.Text = Loc.GetString("ship-computer-console-power",
            ("load", state.PowerLoad), ("capacity", state.PowerSupplyCapacity));
        ModuleList.DisposeAllChildren();

        foreach (var module in state.Modules)
        {
            ModuleList.AddChild(new Label { Text = module.Name });
        }
    }
}
